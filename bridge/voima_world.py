"""Writer for VOIMA world.save (decoded from the game's Save.cs / Load.cs, Assembly-CSharp.dll).

File layout (little endian):
  int raws_end ; raws ... ; int props_start ; tag table [(str name, int end_ptr)] ; property table [(str name, int ptr)]
  strings = 1 length byte + latin-1 bytes. Tag "world" holds flags + slab/card type name lists.
  Slabs are vertical prisms: absolute (x, z) corner polygon, base y0, top y1, a type index into the saved slab name list (1-based).
  Cards: type index into the saved card name list (0-based), position x, y0 (feet), z.
"""
import struct, os


class Writer:
    def __init__(self):
        self.b = bytearray(b'\0\0\0\0'); self.tags = bytearray(); self.props = bytearray()
        self.pre_tag = None; self.pre_tag_i = -1; self.pre_prop = None; self.pre_prop_i = -1

    def i32(self, v): self.b += struct.pack('<i', int(v))
    def f32(self, v): self.b += struct.pack('<f', float(v))
    def bool(self, v): self.b.append(1 if v else 0)
    def s(self, t): t = t.encode('latin-1'); self.b.append(len(t)); self.b += t

    @staticmethod
    def _s(buf, t): t = t.encode('latin-1'); buf.append(len(t)); buf += t

    def prop(self, name):                       # mirrors Save.Property
        if self.pre_prop is not None and self.pre_prop_i != len(self.b):
            self._s(self.props, self.pre_prop); self.props += struct.pack('<i', self.pre_prop_i)
        self.pre_prop = name; self.pre_prop_i = len(self.b)

    def tag(self, name):                        # mirrors Save.Tag
        if self.pre_tag is not None and self.pre_tag_i != len(self.b):
            self._s(self.tags, self.pre_tag); self.tags += struct.pack('<i', len(self.b))
        self.pre_tag = name; self.pre_tag_i = len(self.b)

    def close(self, path):                      # mirrors Save.Close
        self.prop(None); self.tag(None)
        struct.pack_into('<i', self.b, 0, len(self.b))
        self.i32(len(self.b) + len(self.tags))           # exactly as the game writes it
        out = bytes(self.b) + bytes(self.tags) + bytes(self.props)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, 'wb').write(out)


_MAXH = {}
UNIVERSE = ''                                     # the bridge sets this to the universe it writes into


def card_maxhealth(name):
    """the card type's 'Health =' from its .txt in Content or Mods (file name lowercased = card name)"""
    if not _MAXH:
        import glob, re
        root = UNIVERSE
        for f in glob.glob(os.path.join(root, 'Content', '**', '*.txt'), recursive=True) + glob.glob(os.path.join(root, 'Mods', '**', '*.txt'), recursive=True):
            try: t = open(f, encoding='utf-8', errors='ignore').read(4000)
            except OSError: continue
            if not t.startswith('CARD'): continue
            m = re.search(r'^Health\s*=\s*(\d+)', t, re.M)
            if m: _MAXH[os.path.splitext(os.path.basename(f))[0].lower()] = int(m.group(1))
    return _MAXH.get(name.lower(), 10)


def card_health(name, frac=1.0):
    """every inserted card gets at least full health (and at least 100 health). The loader keeps any saved value
    (health = fraction x max health, no clamp on load); the first hit caps it back to the type's max."""
    return max(frac, 100.0 / max(1, card_maxhealth(name)))


def write_world(folder, slabs, cards, player_index=None, time_of_day=0.35, spawn_cards=False, peaceful=True):
    """slabs: dicts {type: name, corners: [(x, z), ...], y0, y1, color: (r, g, b, sat, bright)}
       cards: dicts {type: name, x, y, z}"""
    slab_names = sorted({s['type'] for s in slabs})
    card_names = sorted({c['type'] for c in cards})
    sid = {n: i + 1 for i, n in enumerate(slab_names)}
    cid = {n: i for i, n in enumerate(card_names)}
    w = Writer()
    w.tag('world')
    w.prop('generated by voima'); w.bool(False)          # hand-built: no terrain generation
    w.prop('peaceful beings'); w.bool(peaceful)
    w.prop('card spawning'); w.bool(spawn_cards)
    w.prop('freeze cards'); w.bool(False)
    w.prop('freeze slabs'); w.bool(False)
    w.prop('freeze time'); w.bool(False)
    w.prop('time'); w.f32(time_of_day)
    w.prop('sun angle'); w.f32(7.0)
    w.prop('sky seed'); w.i32(0)
    w.prop('slab types'); w.i32(len(slab_names))
    for n in slab_names: w.s(n)
    w.prop('card types'); w.i32(len(card_names))
    for n in card_names: w.s(n)
    w.prop('recipe unlocks'); w.i32(0)
    n = len(slabs)
    w.tag('slabs')
    w.prop('count'); w.i32(n)
    w.prop('type')
    for s in slabs: w.i32(sid[s['type']])
    centres = []
    for s in slabs:
        cx = sum(p[0] for p in s['corners']) / len(s['corners']); cz = sum(p[1] for p in s['corners']) / len(s['corners'])
        centres.append((cx, cz))
    w.prop('position')
    for (cx, cz), s in zip(centres, slabs): w.f32(cx); w.f32(cz); w.f32(s['y0']); w.f32(s['y1'])
    w.prop('velocity')
    for s in slabs: w.f32(0); w.f32(0); w.f32(0)
    w.prop('grounded')
    for s in slabs: w.bool(True)
    w.prop('corners')
    for s in slabs:
        w.i32(len(s['corners']))
        for x, z in s['corners']: w.f32(x); w.f32(z)
    w.prop('uv offset xz')
    for cx, cz in centres: w.f32(cx); w.f32(cz)
    w.prop('uv offset y')
    for s in slabs: w.f32(s['y0'])
    w.prop('neighbours')
    for s in slabs:
        for _ in range(6): w.i32(-1)
    w.prop('cull boards')
    for s in slabs: w.bool(False); w.bool(False)
    w.prop('colors')
    for s in slabs:
        for v in s.get('color', (1, 1, 1, 1, 0)): w.f32(v)
    w.prop('health')
    for s in slabs: w.f32(1.0)
    if cards:
        m = len(cards)
        w.tag('cards')
        w.prop('count'); w.i32(m)
        w.prop('type')
        for c in cards: w.i32(cid[c['type']])
        w.prop('grounded')
        for c in cards: w.bool(True)
        w.prop('position')
        for c in cards: w.f32(c['x']); w.f32(c['y']); w.f32(c['z'])
        w.prop('velocity')
        for c in cards: w.f32(0); w.f32(0); w.f32(0)
        w.prop('view')
        for c in cards: w.f32(c.get('view', 0)); w.f32(0)
        w.prop('scale')
        for c in cards: w.f32(c.get('scale', 1.0))
        w.prop('health')                                  # saved as a fraction of the type's max health; every card gets >= 100 health
        for c in cards: w.f32(card_health(c['type'], c.get('health', 1.0)))
    w.close(os.path.join(folder, 'world.save'))
    if player_index is not None:                          # Souls/you.save points at the player's card
        s = Writer(); s.tag('soul')
        s.prop('card'); s.i32(player_index)
        s.prop('cheat world edit'); s.i32(-1)
        s.prop('was world editing'); s.bool(False)
        s.prop('cheat universe edit'); s.i32(-1)
        s.prop('was universe editing'); s.bool(False)
        s.close(os.path.join(folder, 'Souls', 'you.save'))
    open(os.path.join(folder, 'details.txt'), 'w', encoding='utf-8', newline='\n').write(
        'Play Time = 0\nCreator = VOIMA Map Maker\nLast Played = 2026 10 28 12 00 00\nSurvival = no\n')
    return slab_names, card_names


def area(pts):
    return sum(pts[i][0] * pts[(i + 1) % len(pts)][1] - pts[(i + 1) % len(pts)][0] * pts[i][1] for i in range(len(pts))) / 2


def poly(t, pts, y0, y1, color=None):
    """any outline (curved, concave or sliced); stored clockwise (negative signed area) like the game's own slabs"""
    pts = [(float(x), float(z)) for x, z in pts]
    if area(pts) > 0:
        pts = pts[::-1]
    s = {'type': t, 'corners': pts, 'y0': y0, 'y1': y1}
    if color: s['color'] = color
    return s


def circle_pts(cx, cz, r, n=40, a0=0.0, a1=None):
    import math
    if a1 is None:
        return [(cx + r * math.cos(a0 + k / n * 2 * math.pi), cz + r * math.sin(a0 + k / n * 2 * math.pi)) for k in range(n)]
    return [(cx + r * math.cos(a0 + (a1 - a0) * k / n), cz + r * math.sin(a0 + (a1 - a0) * k / n)) for k in range(n + 1)]


def ring_sectors(cx, cz, r0, r1, n=40, a0=0.0, a1=6.283185307179586):
    """an annulus (or arc of one) as n convex quads: [(a, b, pts), ...] with a, b the sector angles"""
    import math
    out = []
    for k in range(n):
        a = a0 + (a1 - a0) * k / n; b = a0 + (a1 - a0) * (k + 1) / n
        pts = [(cx + r0 * math.cos(a), cz + r0 * math.sin(a)), (cx + r1 * math.cos(a), cz + r1 * math.sin(a)),
               (cx + r1 * math.cos(b), cz + r1 * math.sin(b)), (cx + r0 * math.cos(b), cz + r0 * math.sin(b))]
        out.append((a, b, pts))
    return out


def rect_outside_disk(x0, x1, z0, z1, R, axis, step=0.5):
    """the rectangle with a round bite of radius R (centred on the origin) taken out of it: points of the outline that fall
    inside the disk slide along `axis` ('x' or 'z') out to the circle, so the edge follows the arc (concave)."""
    import math
    out = []
    corners = [(x0, z0), (x0, z1), (x1, z1), (x1, z0)]
    for i in range(4):
        (ax, az), (bx, bz) = corners[i], corners[(i + 1) % 4]
        n = max(1, int(math.hypot(bx - ax, bz - az) / step))
        for k in range(n):
            x = ax + (bx - ax) * k / n; z = az + (bz - az) * k / n
            if x * x + z * z < R * R:
                if axis == 'x':
                    x = math.copysign(math.sqrt(max(0.0, R * R - z * z)), x if x != 0 else x0 + x1)
                else:
                    z = math.copysign(math.sqrt(max(0.0, R * R - x * x)), z if z != 0 else z0 + z1)
            if not out or abs(out[-1][0] - x) > 1e-4 or abs(out[-1][1] - z) > 1e-4:
                out.append((x, z))
    return out


def rect(t, x0, x1, z0, z1, y0, y1, color=None):
    """axis-aligned box slab, corners in the game's own winding: (x0,z0) (x0,z1) (x1,z1) (x1,z0)"""
    x0, x1 = min(x0, x1), max(x0, x1); z0, z1 = min(z0, z1), max(z0, z1)
    s = {'type': t, 'corners': [(x0, z0), (x0, z1), (x1, z1), (x1, z0)], 'y0': y0, 'y1': y1}
    if color: s['color'] = color
    return s


def ceiling_lamp(x, z, ceil_y, n_lamps=1, case=(1.2, 0.6), case_t=0.1, pocket_h=1.3, wall=0.2, color=(1.0, 1.0, 0.95, 0.2, 0.0)):
    """A real light: a snow slab as the light case set into the ceiling, a small sealed pocket room
    above it, and lamp cards (full health) standing on the case inside the pocket. Lamp light casts no shadows, so it
    shines down through the ceiling. More lamps = brighter. ceil_y = the underside of the ceiling.
    Cut a hole in the ceiling for the case (it fills the hole). Returns (slabs, cards). Lamp light reach is 15 m, and
    lights farther than 70 m or behind the player are switched off by the game."""
    hx, hz = case[0] / 2, case[1] / 2
    top = ceil_y + case_t
    S = [rect('snow', x - hx, x + hx, z - hz, z + hz, ceil_y, top, color)]
    px, pz = max(hx, 0.45 * n_lamps), max(hz, 0.45)                  # pocket interior half sizes
    W = (0.8, 0.8, 0.8, 0.3, 0.0)
    S += [rect('concrete', x - px - wall, x + px + wall, z - pz - wall, z - pz, top, top + pocket_h, W),
          rect('concrete', x - px - wall, x + px + wall, z + pz, z + pz + wall, top, top + pocket_h, W),
          rect('concrete', x - px - wall, x - px, z - pz, z + pz, top, top + pocket_h, W),
          rect('concrete', x + px, x + px + wall, z - pz, z + pz, top, top + pocket_h, W),
          rect('concrete', x - px - wall, x + px + wall, z - pz - wall, z + pz + wall, top + pocket_h, top + pocket_h + wall, W)]
    if px > hx or pz > hz:                                            # floor of the pocket around the case
        S += [rect('concrete', x - px, x + px, z - pz, z - hz, top - case_t, top, W), rect('concrete', x - px, x + px, z + hz, z + pz, top - case_t, top, W),
              rect('concrete', x - px, x - hx, z - hz, z + hz, top - case_t, top, W), rect('concrete', x + hx, x + px, z - hz, z + hz, top - case_t, top, W)]
    C = []
    for k in range(n_lamps):
        lx = x + (k - (n_lamps - 1) / 2) * 0.9
        if abs(lx) < 0.01 and abs(z) < 0.01: lx += 0.05            # cards at exactly (0, 0) are skipped by the loader
        C.append(dict(type='lamp', x=lx, z=z, y=top, health=1.0))
    return [s_ for s_ in S if all(abs(a - b) > 0.01 for a, b in ((s_['y0'], s_['y1']),))], C
